# Programmer Talk

    # Developing apps is more than figuring out what to type into VS Code. 
    # Programmers work together to discuss how to solve problems and explain things to each other. 
    # So it’s important to learn the terminology programmers use.

    # Throughout this course, you’ll learn how to write code, but you’ll also learn the terms you need to talk about code with other developers.

    # You've learned the terms variable and identifier. Keep reading to understand some additional terms.

    # Starting with your first lesson, you wrote code like 6 + 2, which is an example of an expression. 
    # The computer evaluates expressions to produce a value.

    # Expressions by themselves carry a minimal amount of information. 
    # In this project you added the value of statements. 
    # Statements are more like instructions or actions (and they usually contain expressions) and are often referred to informally as lines of code.
#

number_of_dogs = 101

#
    # When you define a variable in Python, it’s called defining a variable. 
    # The instruction it gives to the computer is “Define that the name numberOfDogs has the value 101.”

    # The word let is an example of a keyword. Each keyword has a special meaning in Swift and can't be used as a name.  
    # The let keyword is used to declare a constant. Over time, you’ll be introduced to more Swift keywords.

    # The last part of the statement, = 101, is where you assign a value to the variable. 
    # This is called assignment and the equal sign = is called the assignment operator.

    # Don’t worry about memorizing every new term - it can be overwhelming! 
    # You’ll see these terms used in context during the rest of the course, and you can always find them in the Glossary if you need to refresh your memory.

