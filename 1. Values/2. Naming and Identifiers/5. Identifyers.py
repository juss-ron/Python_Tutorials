# Identifiers

    # In Python, a name is formally called a variable name or an identifier. 
    # But programmers typically use the more informal word name. In this course, you'll become familiar with both terms.

    # Names for variables start with a lowercase letter. 
    # As in the examples below, they can include several words, all run together. 
    # (If there's a space between the words, Python will think each word is a different statement.)

    # To make it easier to read identifiers with multiple words, there should be an underscore inbetween words. 
    # This way of writing out names is called snake_case, because the underscores that connect the words look like they are crawling or slithering along the line of text, much like a snake.
#

number_of_dogs = 6 + 2

number_of_cats = 5 - 1

number_of_turtles = 2 + 1

number_of_hamsters = 1 + 1

total_number_of_animals = number_of_dogs + number_of_cats + number_of_turtles + number_of_hamsters

total_number_of_mammals = number_of_dogs + number_of_cats + number_of_hamsters


