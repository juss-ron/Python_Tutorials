# Choosing Good Names
#
# Choosing good names is a very important programming skill. 
# Programmers want to choose good names so that their code is easy to read and understand.
#
# So far, you’ve used names like number_of_dogs and number_of_cats. 
# These are good names because they clearly describe what they represent.
#
# Imagine if the names had been nd and nc instead (for number_of_dogs and number_of_cats).
# Or even less descriptive names, like n1 and n2.
#
# Python will accept names like this without complaint. 
# But imagine coming back to read that code after vacation. 
# Would you remember what nd or n1 meant? And if you gave the playground to other programmers, how would they figure out what those names were supposed to mean?
# Below is the pet problem using short hand for names.
#

nd = 8
nc = 4
nm = 2
nt = 3
ns = 1
np = 1
nf = 1

total_number_of_animals = nd + nc + nm + nt + ns + np + nf

total_number_of_mammals = nd + nc + nm + np

#
# Why not use short hand for names? 
# One reason is that it can be difficult to understand. 
# It is also hard to interpret. Using words is a lot more flexible and definitely more reliable.
