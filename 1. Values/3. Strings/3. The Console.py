# The Console

    # As a programmer, you get to go behind the scenes, where you’ll see and do things that typical users don’t. 
    # One of those things is called the console. 
    # It has its origin in the days when the only kind of computer interaction was through typing and viewing text.

    # You probably know the word console in the context of video games and TV stands. 
    # In programming, though, the console is a message center that can show details about the way a program is running.

