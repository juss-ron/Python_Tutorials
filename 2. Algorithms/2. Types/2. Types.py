# In Python, every value has a type.

    # Just like types of things in everyday life, each type in Python has its own set of properties and behaviors. 
    # Python's type system is dynamic, meaning the type of a variable is checked during execution, and variables can hold values of different types over time.

    # You've already worked with two of Python's most fundamental types:

        # Strings (str) like "Hello" and "Wimbledon"

        # Integers (int) like 101 and -10

    # Let's look at how Python variables are assigned these types:
# 

string_value = "I am a string"  # The type is str
integer_value = 12             # The type is int

#
    # You've also seen that these types behave differently, especially when using operators like addition (+). 
    # The behavior of an operator depends on the types of the values it is acting upon:
#

1 + 1       # Equals 2 (Integer addition)
"1" + "1"   # Equals "11" (String concatenation)

#
    # The name of the text type in Python is str (short for string).

    # The name of the whole number type you've been using is int (short for integer). 
    # An int value is a whole number with no fractional component. An int can be a positive number, a negative number, or zero.

    # So far, you've only been introduced to a few types, but there are many more to come: 
        # (like float, bool, list, and dict).

    # Learning how to use different types and even creating new types of your own (using classes) will be a big part of learning to program in Python.

    # Imagine a toolbox with a socket wrench, a screwdriver, pliers, and a hammer. 
    # Each type of tool is good for certain tasks—and not at all useful for others. 
    # Every time you learn how to use a new type in Python, you're adding a new tool to your programming toolbox.