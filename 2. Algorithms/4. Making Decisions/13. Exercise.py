# Exercise: Else Practice

    # You’ll recall that else statements hold code that’s run when the result of an if statement is not true. 
    # They can reduce the amount of code needed, and they make it clearer what the flow of a program should be.
#

secret_word = "banana"
guess = "apple"

if secret_word == guess:
    print("Your guess is right.")

if secret_word != guess:
    print("Your guess is wrong.")

